"use client";
// The one-pager you hand your manager on Monday: the five answers per account, the first three moves,
// what is red, and what we still don't know. Every line keeps its source ids. Prints cleanly.
import { Printer } from "lucide-react";
import type { CrmView } from "@/lib/types";
import { fmtDate, fmtMoney } from "./ui";
import { useOps } from "./ops";

export function Brief({ crm }: { crm: CrmView }) {
  const ops = useOps();
  const ids = (xs: string[]) => <span className="mono text-[10px] text-dim">[{[...new Set(xs)].slice(0, 4).map((x) => x.replace(/^[A-Z]:/, "")).join(", ")}]</span>;
  return (
    <div className="brief mx-auto max-w-[900px] space-y-6 bg-panel p-6 print:max-w-none print:bg-white print:p-0 print:text-black">
      <div className="flex items-start justify-between gap-4 border-b border-line pb-4 print:border-black/30">
        <div>
          <div className="label">Monday brief · account date {fmtDate(crm.asOf)}</div>
          <h1 className="mt-1 text-2xl font-semibold">Customer success: {crm.accounts.map((a) => a.name).join(" & ")}</h1>
          <p className="mt-1 text-sm text-muted print:text-black/70">Values in each contract&apos;s currency, never summed across accounts. Ids in [brackets] point to the record behind each line (open them in Account Desk).</p>
        </div>
        <button onClick={() => window.print()} className="mono flex shrink-0 items-center gap-1.5 border border-accent bg-accent px-3 py-1.5 text-[11px] uppercase tracking-wider text-black print:hidden"><Printer size={13} />Print / PDF</button>
      </div>

      {crm.accounts.map((a) => {
        const k = a.kpis;
        const moves = a.moves.map(ops.apply).filter((m) => m.status === "open").slice(0, 3);
        const reds = a.risks.filter((r) => r.level === "red").slice(0, 4);
        return (
          <section key={a.id} className="break-inside-avoid space-y-3">
            <div className="flex flex-wrap items-baseline justify-between gap-2">
              <h2 className="text-lg font-semibold">{a.id} · {a.name}</h2>
              <div className="mono text-sm">health {k.health.score}/100 · renewal {fmtMoney(k.renewal)} {k.daysToRenewal != null ? `in ${k.daysToRenewal} days (${fmtDate(k.termEnds)})` : ""} · docks {k.active}/{k.docks} active</div>
            </div>
            <p className="text-sm"><b>The data says:</b> {a.dataStory} {ids(a.dataStoryCite)}</p>
            <ol className="space-y-1.5 text-sm">
              <li><b>1. Book.</b> {a.answers.book} {ids(k.renewal.cite)}</li>
              <li><b>2. Power.</b> {a.answers.power} {ids(a.people.map((p) => p.id))}</li>
              <li><b>3. First moves.</b>
                <ul className="ml-4 mt-0.5 list-disc">
                  {moves.map((m) => <li key={m.id}>{m.title}: <i>{m.owner}</i>, by {fmtDate(m.due)} (moves {m.dealIds.join(", ")}) {ids(m.cite)}</li>)}
                </ul>
              </li>
              <li><b>4. About to go wrong.</b>
                <ul className="ml-4 mt-0.5 list-disc">
                  {reds.map((r) => <li key={r.id}>{r.title}: turns bad {r.turnsBadOn ? fmtDate(r.turnsBadOn) : "(date not on file)"} {ids(r.cite)}</li>)}
                </ul>
              </li>
              <li><b>5. Still unknown.</b>
                <ul className="ml-4 mt-0.5 list-disc">
                  {a.gaps.slice(0, 3).map((g) => <li key={g.id}>{g.question} Ask: {g.whoCanTell}. {ids(g.cite)}</li>)}
                </ul>
              </li>
            </ol>
          </section>
        );
      })}
      <div className="border-t border-line pt-3 text-[11px] text-dim print:border-black/30">Generated by Account Desk from the Account Quest MCP · data version {crm.generatedAt.slice(0, 16).replace("T", " ")} UTC</div>
    </div>
  );
}
